#!/usr/bin/env python3
"""Builds the mobile apps' Agent logos from the desktop's assets/icons/agent-*.svg.

Generated files are checked in:

- iOS: mobile/ios/Yttt/Assets.xcassets/Agents/agent-<name>.imageset, the SVG
  kept as a vector. Monochrome logos are templates, tinted with the text colour,
  as the desktop paints them.
- Android: mobile/android/app/src/main/res/drawable/agent_<name>.xml, vector
  drawables converted from the SVG's paths, rectangles, circles and linear
  gradients, in a square viewport. Monochrome ones are drawn black for a tint.

Which logos are coloured follows the desktop (src/ui/workbench/shell/sidebar.rs).
Usage: scripts/build-mobile-agent-logos.py
"""

import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "assets/icons"
IOS_DIR = ROOT / "mobile/ios/Yttt/Assets.xcassets/Agents"
ANDROID_DIR = ROOT / "mobile/android/app/src/main/res/drawable"

COLORED = {"codex", "claude"}
LOGOS = ["codex", "claude", "grok", "opencode", "pi", "omp"]
SVG = "{http://www.w3.org/2000/svg}"
HEADER = "<!-- Generated by scripts/build-mobile-agent-logos.py from assets/icons/agent-{name}.svg. -->\n"


def fail(message):
    sys.exit(f"build-mobile-agent-logos: {message}")


def color(value, opacity=None):
    """An SVG colour as Android's #AARRGGBB; currentColor (or none given) is black, for a tint."""
    if value in (None, "currentColor"):
        h = "000000"
    else:
        h = value.lstrip("#")
        if len(h) == 3:
            h = "".join(c * 2 for c in h)
        if not re.fullmatch(r"[0-9a-fA-F]{6}", h):
            fail(f"colour not understood: {value}")
    alpha = 255 if opacity is None else round(float(opacity) * 255)
    return f"#{alpha:02X}{h.upper()}"


def rect_path(x, y, w, h, r):
    if r <= 0:
        return f"M{x},{y}h{w}v{h}h{-w}z"
    r = min(r, w / 2, h / 2)
    return (f"M{x + r},{y}h{w - 2 * r}a{r},{r} 0 0 1 {r},{r}v{h - 2 * r}a{r},{r} 0 0 1 {-r},{r}"
            f"h{-(w - 2 * r)}a{r},{r} 0 0 1 {-r},{-r}v{-(h - 2 * r)}a{r},{r} 0 0 1 {r},{-r}z")


def circle_path(cx, cy, r):
    return f"M{cx - r},{cy}a{r},{r} 0 1 0 {2 * r},0a{r},{r} 0 1 0 {-2 * r},0z"


def num(element, name, default=0.0):
    return float(element.get(name, default))


def android(name, text):
    root = ET.fromstring(text)
    vx, vy, vw, vh = (float(v) for v in root.get("viewBox").split())
    side = max(vw, vh)
    # Centre a non-square viewBox in a square viewport.
    dx, dy = (side - vw) / 2 - vx, (side - vh) / 2 - vy
    inherited = root.get("fill")
    gradients = {}
    for gradient in root.iter(f"{SVG}linearGradient"):
        if gradient.get("gradientUnits") != "userSpaceOnUse":
            fail(f"{name}: only userSpaceOnUse gradients are converted")
        stops = [(float(s.get("offset", 0)), s.get("stop-color")) for s in gradient.findall(f"{SVG}stop")]
        gradients[gradient.get("id")] = (gradient, stops)
    paths = []
    for element in root.iter():
        tag = element.tag.replace(SVG, "")
        if tag == "path":
            data = element.get("d")
        elif tag == "rect":
            data = rect_path(num(element, "x"), num(element, "y"), num(element, "width"), num(element, "height"), num(element, "rx"))
        elif tag == "circle":
            data = circle_path(num(element, "cx"), num(element, "cy"), num(element, "r"))
        else:
            continue
        fill = element.get("fill", inherited)
        attrs = [f'android:pathData="{data}"']
        if element.get("fill-rule") == "evenodd" or (element.get("fill-rule") is None and root.get("fill-rule") == "evenodd"):
            attrs.append('android:fillType="evenOdd"')
        body = ""
        if fill and fill.startswith("url(#"):
            gradient, stops = gradients[fill[5:-1]]
            items = "".join(f'\n                <item android:offset="{o:g}" android:color="{color(c)}"/>' for o, c in stops)
            body = (f'\n        <aapt:attr name="android:fillColor">\n            <gradient android:type="linear"'
                    f' android:startX="{gradient.get("x1")}" android:startY="{gradient.get("y1")}"'
                    f' android:endX="{gradient.get("x2")}" android:endY="{gradient.get("y2")}">{items}\n            </gradient>\n        </aapt:attr>\n    ')
        else:
            colour = color(fill, element.get("opacity")) if name in COLORED else color(None, element.get("opacity"))
            attrs.append(f'android:fillColor="{colour}"')
        attrs_text = "\n        ".join(attrs)
        paths.append(f"    <path\n        {attrs_text}>{body}</path>" if body else f"    <path\n        {attrs_text}/>")
    if not paths:
        fail(f"{name}: no shapes found")
    return (f'<?xml version="1.0" encoding="utf-8"?>\n{HEADER.format(name=name)}'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    xmlns:aapt="http://schemas.android.com/aapt"\n'
            f'    android:width="24dp"\n    android:height="24dp"\n'
            f'    android:viewportWidth="{side:g}"\n    android:viewportHeight="{side:g}">\n'
            f'    <group android:translateX="{dx:g}" android:translateY="{dy:g}">\n'
            + "\n".join("    " + p.replace("\n", "\n    ") for p in paths)
            + "\n    </group>\n</vector>\n")


def ios(name, text):
    out = IOS_DIR / f"agent-{name}.imageset"
    out.mkdir(parents=True, exist_ok=True)
    clean = re.sub(r"<!--.*?-->\s*", "", text, flags=re.S)
    if name not in COLORED:
        clean = clean.replace("currentColor", "#000000")
    (out / f"agent-{name}.svg").write_text(clean)
    properties = {"preserves-vector-representation": True}
    if name not in COLORED:
        properties["template-rendering-intent"] = "template"
    (out / "Contents.json").write_text(json.dumps({
        "images": [{"filename": f"agent-{name}.svg", "idiom": "universal"}],
        "info": {"author": "xcode", "version": 1},
        "properties": properties,
    }, indent=2) + "\n")


def main():
    IOS_DIR.mkdir(parents=True, exist_ok=True)
    (IOS_DIR / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
    ANDROID_DIR.mkdir(parents=True, exist_ok=True)
    for name in LOGOS:
        text = (SOURCES / f"agent-{name}.svg").read_text()
        ios(name, text)
        (ANDROID_DIR / f"agent_{name}.xml").write_text(android(name, text))
    print(f"{len(LOGOS)} logos: {IOS_DIR.relative_to(ROOT)}, {ANDROID_DIR.relative_to(ROOT)}/agent_*.xml")


if __name__ == "__main__":
    main()
