#!/usr/bin/env python3
"""Builds the mobile app icons from the desktop icon's SVG.

The source is assets/app-icon/source/yttt-icon.svg: a dark rounded tile with a
silver glyph (the Y, the prompt and the cursor). Generated files are checked in:

- iOS: mobile/ios/Yttt/Assets.xcassets/AppIcon.appiconset/AppIcon.png, 1024 x
  1024 and opaque, the tile filling it edge to edge: iOS rounds the corners.
- Android, as vector drawables (adaptive icons, API 26+):
  - ic_launcher_background: the tile's gradient;
  - ic_launcher_foreground: the glyph, the tile mapped to the 72 dp that show
    through the mask, so the glyph keeps the desktop proportions;
  - ic_launcher_monochrome: the glyph alone, for themed icons (Android 13+);
  - ic_stat_yttt: the glyph as a white silhouette for notifications.

Needs rsvg-convert (librsvg) and magick (ImageMagick), as scripts/build-app-icons.sh.
Usage: scripts/build-mobile-icons.py
"""

import json
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets/app-icon/source/yttt-icon.svg"
IOS_SET = ROOT / "mobile/ios/Yttt/Assets.xcassets/AppIcon.appiconset"
ANDROID_RES = ROOT / "mobile/android/app/src/main/res"

SVG = "{http://www.w3.org/2000/svg}"
HEADER = "<!-- Generated by scripts/build-mobile-icons.py from assets/app-icon/source/yttt-icon.svg. -->\n"


def fail(message):
    sys.exit(f"build-mobile-icons: {message}")


def transform(text):
    """`translate(x y) scale(s)` as (tx, ty, s); either part may be missing."""
    tx = ty = 0.0
    s = 1.0
    if m := re.search(r"translate\(\s*([-\d.]+)[\s,]+([-\d.]+)\s*\)", text or ""):
        tx, ty = float(m[1]), float(m[2])
    if m := re.search(r"scale\(\s*([-\d.]+)\s*\)", text or ""):
        s = float(m[1])
    return tx, ty, s


def stops(gradient):
    colors = [stop.get("stop-color") for stop in gradient.findall(f"{SVG}stop")]
    if len(colors) != 2:
        fail(f"gradient {gradient.get('id')}: expected two stops, found {len(colors)}")
    return colors


def bbox(path):
    """Bounds of a path made of absolute M, L, H, V and Z commands."""
    x = y = 0.0
    xs, ys = [], []
    for command, args in re.findall(r"([MLHVZ])([^MLHVZ]*)", path):
        numbers = [float(n) for n in re.findall(r"[-\d.]+", args)]
        if command in "ML":
            for i in range(0, len(numbers), 2):
                x, y = numbers[i], numbers[i + 1]
                xs.append(x)
                ys.append(y)
        elif command == "H":
            x = numbers[-1]
            xs.append(x)
        elif command == "V":
            y = numbers[-1]
            ys.append(y)
    if re.search(r"[^MLHVZ\d.\s,-]", path):
        fail(f"path uses commands this script does not read: {path}")
    return min(xs), min(ys), max(xs), max(ys)


def read_source():
    tree = ET.parse(SOURCE).getroot()
    gradients = {g.get("id"): g for g in tree.iter(f"{SVG}linearGradient")}
    for gradient in gradients.values():
        if (gradient.get("x1"), gradient.get("y1"), gradient.get("x2"), gradient.get("y2")) != ("0", "0", ".7", "1"):
            fail(f"gradient {gradient.get('id')}: expected x1=0 y1=0 x2=.7 y2=1")
    outer = tree.find(f"{SVG}g")
    tile = outer.find(f"{SVG}rect")
    glyph = outer.find(f"{SVG}g")
    paths = [p.get("d") for p in glyph.findall(f"{SVG}path")]
    if len(paths) != 3:
        fail(f"expected the glyph's three paths, found {len(paths)}")
    return {
        "tile_size": float(tile.get("width")),
        "tile_colors": stops(gradients["tile"]),
        "glyph_colors": stops(gradients["silver"]),
        "glyph_transform": glyph.get("transform"),
        "paths": paths,
    }


def ios_icon(src, out):
    """The tile, square and edge to edge, with the glyph where the desktop has it."""
    size = src["tile_size"]
    t, g = src["tile_colors"], src["glyph_colors"]
    paths = "\n".join(f'    <path d="{d}"/>' for d in src["paths"])
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 {size:g} {size:g}">
  <defs>
    <linearGradient id="tile" x1="0" y1="0" x2=".7" y2="1"><stop stop-color="{t[0]}"/><stop offset="1" stop-color="{t[1]}"/></linearGradient>
    <linearGradient id="silver" x1="0" y1="0" x2=".7" y2="1"><stop stop-color="{g[0]}"/><stop offset="1" stop-color="{g[1]}"/></linearGradient>
  </defs>
  <rect width="{size:g}" height="{size:g}" fill="url(#tile)"/>
  <g transform="{src['glyph_transform']}" fill="url(#silver)">
{paths}
  </g>
</svg>
"""
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        svg_file = Path(tmp) / "icon.svg"
        svg_file.write_text(svg)
        rgba = Path(tmp) / "icon.png"
        subprocess.run(["rsvg-convert", "--output", str(rgba), str(svg_file)], check=True)
        # App Store icons must have no alpha channel.
        subprocess.run(["magick", str(rgba), "-background", t[1], "-alpha", "remove", "-alpha", "off",
                        f"PNG24:{out / 'AppIcon.png'}"], check=True)
    (out / "Contents.json").write_text(json.dumps({
        "images": [{"filename": "AppIcon.png", "idiom": "universal", "platform": "ios", "size": "1024x1024"}],
        "info": {"author": "xcode", "version": 1},
    }, indent=2) + "\n")
    (out.parent / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
    info = subprocess.run(["magick", "identify", "-format", "%w %h %[opaque] %[channels]", str(out / "AppIcon.png")],
                          capture_output=True, text=True, check=True).stdout.split()
    if info[:3] != ["1024", "1024", "True"] or "a" in info[3]:
        fail(f"iOS icon is not 1024 x 1024 and opaque: {info}")


def color(hex_color):
    """#rgb or #rrggbb as Android's #AARRGGBB."""
    h = hex_color.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return f"#FF{h.upper()}"


def gradient_fill(x0, y0, x1, y1, colors):
    """A linear gradient as SVG's x2=.7 y2=1 over the box (x0, y0)-(x1, y1)."""
    return f"""        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="{x0:g}" android:startY="{y0:g}"
                android:endX="{x0 + 0.7 * (x1 - x0):g}" android:endY="{y1:g}"
                android:startColor="{color(colors[0])}"
                android:endColor="{color(colors[1])}"/>
        </aapt:attr>"""


def glyph_paths(src, silver):
    out = []
    for d in src["paths"]:
        if silver:
            # The SVG's gradient is per shape: each path's own bounds.
            x0, y0, x1, y1 = bbox(d)
            out.append(f'        <path android:pathData="{d}">\n{gradient_fill(x0, y0, x1, y1, src["glyph_colors"])}\n        </path>')
        else:
            out.append(f'        <path android:pathData="{d}" android:fillColor="#FFFFFFFF"/>')
    return "\n".join(out)


def vector(size_dp, viewport, body):
    return f"""<?xml version="1.0" encoding="utf-8"?>
{HEADER}<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
{body}
</vector>
"""


def glyph_group(src, offset, scale, silver):
    """The glyph with the SVG's own transform, inside the tile placed at offset, scaled."""
    gx, gy, gs = transform(src["glyph_transform"])
    return f"""    <group android:translateX="{offset:g}" android:translateY="{offset:g}" android:scaleX="{scale:.6f}" android:scaleY="{scale:.6f}">
    <group android:translateX="{gx:g}" android:translateY="{gy:g}" android:scaleX="{gs}" android:scaleY="{gs}">
{glyph_paths(src, silver)}
    </group>
    </group>"""


def android_icons(src, res):
    drawable = res / "drawable"
    anydpi = res / "mipmap-anydpi-v26"
    drawable.mkdir(parents=True, exist_ok=True)
    anydpi.mkdir(parents=True, exist_ok=True)
    # Adaptive icons are 108 dp; the mask shows the middle 72 dp, where the
    # tile goes.
    scale = 72 / src["tile_size"]
    tile_end = 18 + 72
    background = f"""    <path android:pathData="M0,0h108v108h-108z">
{gradient_fill(18, 18, tile_end, tile_end, src["tile_colors"])}
    </path>"""
    (drawable / "ic_launcher_background.xml").write_text(vector(108, 108, background))
    (drawable / "ic_launcher_foreground.xml").write_text(vector(108, 108, glyph_group(src, 18, scale, silver=True)))
    (drawable / "ic_launcher_monochrome.xml").write_text(vector(108, 108, glyph_group(src, 18, scale, silver=False)))
    (anydpi / "ic_launcher.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
{HEADER}<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
""")
    # Notification icon: the glyph alone, as large as fits 22 of the 24 dp.
    boxes = [bbox(d) for d in src["paths"]]
    x0, y0 = min(b[0] for b in boxes), min(b[1] for b in boxes)
    x1, y1 = max(b[2] for b in boxes), max(b[3] for b in boxes)
    fit = 22 / max(x1 - x0, y1 - y0)
    tx = (24 - (x1 - x0) * fit) / 2 - x0 * fit
    ty = (24 - (y1 - y0) * fit) / 2 - y0 * fit
    status = f"""    <group android:translateX="{tx:.4f}" android:translateY="{ty:.4f}" android:scaleX="{fit:.6f}" android:scaleY="{fit:.6f}">
{glyph_paths(src, silver=False)}
    </group>"""
    (drawable / "ic_stat_yttt.xml").write_text(vector(24, 24, status))


def main():
    src = read_source()
    ios_icon(src, IOS_SET)
    android_icons(src, ANDROID_RES)
    print(f"iOS: {IOS_SET.relative_to(ROOT)}/AppIcon.png")
    print(f"Android: {ANDROID_RES.relative_to(ROOT)}/drawable/ic_launcher_*.xml, ic_stat_yttt.xml")


if __name__ == "__main__":
    main()
